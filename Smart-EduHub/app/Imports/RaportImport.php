<?php

namespace App\Imports;

use App\Models\RaportIndustri;
use App\Models\RaportCapaianPembelajaran;
use App\Models\RaportUjiSertifikasi;
use App\Models\Student;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\DB;
use Maatwebsite\Excel\Concerns\ToCollection;
use Maatwebsite\Excel\Concerns\WithHeadingRow;

class RaportImport implements ToCollection, WithHeadingRow
{
    public int $imported = 0;
    public int $errors = 0;
    public array $errorMessages = [];

    public function collection(Collection $rows)
    {
        foreach ($rows as $index => $row) {
            $rowNumber = $index + 2; // Header at row 1

            // Support various heading keys generated by Maatwebsite
            $nisVal = trim((string)($row['nis_id_siswa'] ?? $row['nis_siswa'] ?? $row['nis'] ?? $row['id_siswa'] ?? ''));

            if (empty($nisVal)) {
                continue; // Skip empty rows
            }

            // Find Student
            $student = Student::where('nis_siswa', $nisVal)
                ->orWhere('id_siswa', $nisVal)
                ->orWhere('nisn', $nisVal)
                ->orWhere('id', $nisVal)
                ->first();

            if (!$student) {
                $this->errors++;
                $this->errorMessages[] = "Baris #{$rowNumber}: Siswa dengan NIS/ID '{$nisVal}' tidak ditemukan.";
                continue;
            }

            $tahunPelajaran  = trim((string)($row['tahun_pelajaran'] ?? date('Y') . '/' . (date('Y') + 1) . '_Genap'));
            $tingkat         = trim((string)($row['tingkat'] ?? ''));
            $programKeahlian = trim((string)($row['program_keahlian'] ?? ''));
            $trainerName     = trim((string)($row['nama_trainer'] ?? $row['trainer_name'] ?? ''));
            $trainerNoSerti  = trim((string)($row['no_serti_trainer'] ?? $row['trainer_no_serti'] ?? ''));
            $trainerNbm      = trim((string)($row['nbm_trainer'] ?? $row['trainer_nbm'] ?? ''));
            $catatan         = trim((string)($row['catatan'] ?? ''));

            DB::beginTransaction();
            try {
                // Update existing or create new raport
                $raport = RaportIndustri::updateOrCreate(
                    [
                        'student_id'      => $student->id,
                        'tahun_pelajaran' => $tahunPelajaran,
                    ],
                    [
                        'angkatan_id'      => $student->angkatan_id,
                        'tingkat'          => $tingkat ?: null,
                        'program_keahlian' => $programKeahlian ?: null,
                        'trainer_name'     => $trainerName ?: null,
                        'trainer_no_serti' => $trainerNoSerti ?: null,
                        'trainer_nbm'      => $trainerNbm ?: null,
                        'catatan'          => $catatan ?: null,
                    ]
                );

                // Re-create Capaian Pembelajaran
                $raport->capaianPembelajaran()->delete();
                $aspekNo = 1;

                // Loop up to 10 potential aspects in row
                for ($i = 1; $i <= 10; $i++) {
                    $namaKey = "aspek_{$i}_nama";
                    $predKey = "aspek_{$i}_predikat_abcd";
                    $ketKey  = "aspek_{$i}_keterangan";

                    // Fallback keys
                    if (!isset($row[$namaKey])) $namaKey = "aspek_{$i}_penilaian";
                    if (!isset($row[$predKey])) $predKey = "aspek_{$i}_predikat";

                    $nama = trim((string)($row[$namaKey] ?? ''));
                    $pred = strtoupper(trim((string)($row[$predKey] ?? '')));
                    $ket  = trim((string)($row[$ketKey] ?? ''));

                    if (!empty($nama) && in_array($pred, ['A', 'B', 'C', 'D'])) {
                        RaportCapaianPembelajaran::create([
                            'raport_id'       => $raport->id,
                            'no'              => $aspekNo++,
                            'aspek_penilaian' => $nama,
                            'predikat'        => $pred,
                            'keterangan'      => $ket ?: null,
                        ]);
                    }
                }

                // Default 5 aspek if none provided in Excel
                if ($aspekNo === 1) {
                    $defaultAspek = [
                        'Sikap dan kemauan kerja'         => 'A',
                        'Kreatif dan inovatif kerja'      => 'A',
                        'Ketrampilan menggunakan Alat'   => 'B',
                        'Kedisiplinan dan tanggung jawab' => 'A',
                        'Kemauan Melaksanakan tugas'     => 'A',
                    ];
                    $defNo = 1;
                    foreach ($defaultAspek as $nama => $pred) {
                        RaportCapaianPembelajaran::create([
                            'raport_id'       => $raport->id,
                            'no'              => $defNo++,
                            'aspek_penilaian' => $nama,
                            'predikat'        => $pred,
                            'keterangan'      => null,
                        ]);
                    }
                }

                // Re-create Uji Sertifikasi
                $raport->ujiSertifikasi()->delete();
                $sertiNo = 1;

                for ($j = 1; $j <= 10; $j++) {
                    $ujianKey  = "sertifikasi_{$j}_ujian";
                    $noSertKey = "sertifikasi_{$j}_no_serti";
                    $statusKey = "sertifikasi_{$j}_status_lulustidak_lulus";

                    if (!isset($row[$ujianKey]))  $ujianKey  = "uji_sertifikasi_{$j}_nama";
                    if (!isset($row[$statusKey])) $statusKey = "sertifikasi_{$j}_status";

                    $ujian  = trim((string)($row[$ujianKey] ?? ''));
                    $noSert = trim((string)($row[$noSertKey] ?? ''));
                    $status = strtoupper(trim((string)($row[$statusKey] ?? '')));

                    if (!empty($ujian)) {
                        RaportUjiSertifikasi::create([
                            'raport_id'  => $raport->id,
                            'no'         => $sertiNo++,
                            'nama_ujian' => $ujian,
                            'no_serti'   => $noSert ?: null,
                            'status'     => in_array($status, ['LULUS', 'TIDAK LULUS']) ? $status : 'LULUS',
                        ]);
                    }
                }

                DB::commit();
                $this->imported++;
            } catch (\Exception $e) {
                DB::rollBack();
                $this->errors++;
                $this->errorMessages[] = "Baris #{$rowNumber} (Siswa {$student->nama_lengkap}): Gagal disimpan - " . $e->getMessage();
            }
        }
    }
}
